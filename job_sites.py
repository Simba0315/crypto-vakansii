NOT_READ = ['ZipRecruiter', 'Monster', 'CareerBuilder', 'Adzuna', 'Talent.com', 'SuperJob']        # their pricing pages showed a bot check or an error on READ


def check():
    names = [x["name"] for x in SITES]
    assert names == sorted(names, key=str.lower), "keep the sites in alphabetical order"
    for x in SITES:
        assert x["kind"] in FOR and x["free"][0] in KINDS and x["free"][1], x["name"]
        for k in ("price", "runs", "billing", "extras"): assert isinstance(x[k], str), (x["name"], k)
        assert x["url"].startswith("https://") and x["sources"], x["name"]
        for u, when in x["sources"]: assert u.startswith("https://") and when, (x["name"], u)
    return len(SITES)


